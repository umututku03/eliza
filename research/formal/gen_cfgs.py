#!/usr/bin/env python3
"""Write the MC_<policy>_<scenario>.cfg model configs (the bounds live here; README.md lists them).

Usage: python3 -I gen_cfgs.py      (writes into this directory)
"""
import os

POLICIES = ["full", "nonce_only", "verify_binary", "none"]

BASE = dict(
    NI=2, SharedToken=False, Reinclude=False,
    MaxNonce=3, MaxTx=4, MaxBlocks=5,
    MaxReorgs=0, MaxDepth=1, MaxLag=0, MaxDrops=0, MaxLostAcks=0, MaxHides=0,
    MaxReq=3, MaxStatus=1, MaxRecs=3, K=2, N=3,
    AgentStopsOnAsk=False, AgentSequential=True, PriorityMining=False, TimelyInclusion=False,
)

SAFETY = "INVARIANTS TypeOK AtMostOnce NoFalseConfirm NoActOnOrphan"
LIVENESS = "PROPERTIES EventuallyResolved EventuallyCorrect"

# One fault family per scenario (the chain-faults cells), plus compound and shared-token variants.
SCENARIOS = {
    "hidden":   (dict(MaxHides=1), "receipt_hidden: one receipt hidden, later shown again"),
    "dropped":  (dict(MaxDrops=1), "sale_dropped: one pooled transaction dropped"),
    "lostack":  (dict(MaxLostAcks=1), "lost acknowledgement: one accepted send reported as an RPC error"),
    "stale":    (dict(MaxLag=2), "rpc_stale: the RPC view lags the head by up to 2 blocks"),
    "reorg":    (dict(MaxReorgs=1, MaxDepth=2, MaxBlocks=6), "sale_reorged: one reorg of depth <= 2, no re-inclusion"),
    "reincl":   (dict(MaxReorgs=1, MaxDepth=2, MaxBlocks=6, Reinclude=True),
                 "sale_reorged_reincluded: one reorg of depth <= 2, orphans return to the mempool"),
    "hidden_reorg": (dict(MaxHides=1, MaxReorgs=1, MaxBlocks=6), "compound: hidden receipt then a depth-1 reorg"),
    "stale_reorg":  (dict(MaxLag=1, MaxReorgs=1, MaxBlocks=6), "compound: lag <= 1 and a depth-1 reorg"),
    "dropped_shared": (dict(MaxDrops=1, SharedToken=True), "sale_dropped, both intents credit the same token"),
    "stale_shared":   (dict(MaxLag=2, SharedToken=True), "rpc_stale, both intents credit the same token"),
}

# Agent variant: an interleaving agent that may return to an earlier intent after requesting a later one
# (the default agent is a sequential naive re-sender: it repeats the current intent until success, may move on,
# and never returns to an earlier intent).
SEQUENTIAL = {
    "nofault_any": (dict(AgentSequential=False), "no fault, interleaving agent"),
    "hidden_any":  (dict(MaxHides=1, AgentSequential=False), "receipt_hidden, interleaving agent"),
}

# Liveness: fairness (LiveSpec), the agent stops after ask_user, timely inclusion, priority mining.
LIVE_BASE = dict(AgentStopsOnAsk=True, PriorityMining=True, TimelyInclusion=True, MaxStatus=0,
                 NI=1, MaxReq=5, MaxTx=5, MaxBlocks=6, MaxRecs=2)
LIVE = {
    "live_hidden":  (dict(MaxHides=1), "liveness under a hidden receipt"),
    "live_dropped": (dict(MaxDrops=1), "liveness under a dropped transaction"),
    "live_lostack": (dict(MaxLostAcks=1), "liveness under a lost acknowledgement"),
    "live_stale":   (dict(MaxLag=2), "liveness under a lagging RPC view"),
    "live_reorg":   (dict(MaxReorgs=1, MaxBlocks=7), "liveness under a depth-1 reorg, no re-inclusion"),
    "live_reincl":  (dict(MaxReorgs=1, MaxBlocks=7, Reinclude=True), "liveness under a depth-1 reorg with re-inclusion"),
}


def fmt(v):
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, str):
        return f'"{v}"'
    return str(v)


def write(policy, scen, over, desc, spec, props):
    c = dict(BASE, **over)
    lines = [f"\\* {policy} / {scen}: {desc}. Generated by gen_cfgs.py.", f"SPECIFICATION {spec}", "CONSTANTS",
             f'  Policy = "{policy}"']
    lines += [f"  {k} = {fmt(v)}" for k, v in c.items()]
    lines += [props, "CHECK_DEADLOCK FALSE", ""]
    name = f"MC_{policy}_{scen}.cfg"
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), name), "w") as f:
        f.write("\n".join(lines))
    return name


def main():
    names = []
    for p in POLICIES:
        for s, (o, d) in {**SCENARIOS, **SEQUENTIAL}.items():
            names.append(write(p, s, o, d, "Spec", SAFETY))
        if p == "full":  # liveness on the full layer only (the baselines' liveness gaps show in safety traces)
            for s, (o, d) in LIVE.items():
                names.append(write(p, s, dict(LIVE_BASE, **o), d, "LiveSpecFull", LIVENESS))
    # Validates the explicit enabledness predicates of FairnessFull against ENABLED (small model, slow check).
    names.append(write("full", "enabled_check", dict(LIVE_BASE, MaxHides=1, MaxDrops=1, MaxReorgs=1, MaxBlocks=5, MaxReq=3, MaxTx=3),
                       "EnabledMatches on a small model", "Spec", "INVARIANTS EnabledMatches"))
    print("\n".join(names))


if __name__ == "__main__":
    main()
